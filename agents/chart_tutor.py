# -*- coding: utf-8 -*-
"""
차트 튜터 — 지금 차트를 사람 말로 읽어주고, 보는 법을 가르친다 (규칙 기반, LLM 무사용)

interpret(df): enrich()된 df의 마지막 상태를 6개 관점(추세/흐름/볼린저/RSI/MACD/거래량)으로
  각각 [지금 상태 → 어떻게 읽는가 → 공부 포인트] 구조로 해석.
LESSONS: 차트 공부방 — 각 지표가 무엇이고 왜 보는지, 흔한 함정.
"""
from __future__ import annotations

import pandas as pd


def interpret(df: pd.DataFrame, unit: str = "원") -> list[dict]:
    """enrich()된 df → [{"title", "state", "read", "tip"}] 목록."""
    last = df.iloc[-1]
    c = float(last["close"])
    o = float(last["open"])
    ma5, ma20 = float(last["ma5"]), float(last["ma20"])
    ma60 = float(last["ma60"]) if pd.notna(last["ma60"]) else None
    rsi = float(last["rsi"])
    pct_b = float(last["pct_b"])
    bw = float(last["bandwidth"]) if pd.notna(last["bandwidth"]) else None
    rvol = float(last["rvol"])
    hist = float(last["macd_hist"])
    hist_prev = float(df["macd_hist"].iloc[-4]) if len(df) >= 4 else hist
    obv_up = bool(last["obv"] > last["obv_ma20"]) if pd.notna(last["obv_ma20"]) else None
    ret5 = c / float(df["close"].iloc[-6]) - 1 if len(df) >= 6 else 0.0
    ret20 = c / float(df["close"].iloc[-21]) - 1 if len(df) >= 21 else 0.0
    bw_min60 = float(df["bandwidth"].tail(60).min()) if bw is not None else None

    out: list[dict] = []
    pfx = "{:,.0f}" + unit

    # ── 1. 추세 (이동평균선) ──────────────────────────────────────────────
    if ma60 is not None and ma5 > ma20 > ma60:
        st_, rd = "정배열 (MA5 > MA20 > MA60)", \
            "단기·중기·장기 평균 매수가가 계단처럼 올라선 상승 구조예요. 최근에 산 사람일수록 비싸게 샀는데도 주가가 그 위에 있다는 뜻 — 시장이 계속 웃돈을 주고 있는 상태."
    elif ma60 is not None and ma5 < ma20 < ma60:
        st_, rd = "역배열 (MA5 < MA20 < MA60)", \
            "평균 매수가가 계단처럼 내려앉은 하락 구조예요. 위쪽에 물린 물량(매물대)이 겹겹이 쌓여 있어 반등 때마다 본전 매도가 나오기 쉬운 상태."
    else:
        st_, rd = "혼조 배열", "이평선이 서로 얽혀 있어요. 추세가 만들어지는 중이거나 무너지는 중 — 방향이 정해질 때까지 신호의 신뢰도가 낮은 구간."
    _pos = "위" if c > ma20 else "아래"
    rd += f" 현재가({pfx.format(c)})는 20일선({pfx.format(ma20)}) {_pos}."
    out.append({
        "title": "📈 추세 — 이동평균선", "state": st_, "read": rd,
        "tip": "이평선은 'N일간 산 사람들의 평균 단가'. 주가가 그 위에 있으면 최근 매수자 대부분이 수익 중이라 매물 압력이 약합니다. 20일선은 한 달 세력선, 60일선은 분기 추세선으로 불러요.",
    })

    # ── 2. 최근 흐름 ─────────────────────────────────────────────────────
    _cd = "양봉(종가>시가)" if c >= o else "음봉(종가<시가)"
    out.append({
        "title": "🕯️ 최근 흐름 — 캔들", "state": f"5일 {ret5:+.1%} · 20일 {ret20:+.1%} · 오늘 {_cd}",
        "read": ("단기와 한 달 흐름이 모두 상방" if ret5 > 0 and ret20 > 0 else
                 "한 달 상승 속 단기 조정" if ret5 <= 0 < ret20 else
                 "한 달 하락 속 단기 반등 시도" if ret5 > 0 >= ret20 else
                 "단기·한 달 모두 하방") + "이에요.",
        "tip": "캔들 하나보다 5일·20일 묶음의 방향이 중요해요. 양봉 = 그날 매수세 승리, 음봉 = 매도세 승리. 긴 꼬리는 그 가격대에서 반대 세력이 나타났다는 흔적.",
    })

    # ── 3. 볼린저밴드 ────────────────────────────────────────────────────
    if pct_b > 1.0:
        st_, rd = f"%B {pct_b:.2f} — 밴드 상단 돌파", \
            "통계적으로 상위 2.5% 영역까지 올라왔어요. 거래량이 함께 터졌다면 '강한 추세의 시작'일 수 있지만, 거래량 없이면 과열 후 되돌림이 흔합니다."
    elif pct_b > 0.8:
        st_, rd = f"%B {pct_b:.2f} — 밴드 상단부", "밴드 위쪽에서 움직이는 강세 구간이에요. 상단을 타고 가는 '밴드 워킹'은 추세장이 보이는 전형적 모습."
    elif pct_b < 0.2:
        st_, rd = f"%B {pct_b:.2f} — 밴드 하단부", "통계적으로 싼 영역이지만, 하락 추세에선 밴드 하단을 타고 계속 내려가기도 해요(하단 워킹). 반등 신호와 함께 볼 것."
    else:
        st_, rd = f"%B {pct_b:.2f} — 밴드 중앙권", "평균 근처의 평범한 위치예요. 볼린저만으론 방향 정보가 약한 구간."
    if bw is not None and bw_min60 is not None and bw <= bw_min60 * 1.1:
        rd += " 그리고 밴드폭이 60일 최저 수준까지 좁혀졌어요 — 변동성 압축(스퀴즈)은 곧 큰 방향 결정이 나온다는 예고편인 경우가 많습니다."
    out.append({
        "title": "🎈 볼린저밴드 — 가격의 위치", "state": st_, "read": rd,
        "tip": "볼린저밴드 = 20일 평균 ± 2×표준편차. 주가가 통계적으로 어디까지 벗어났는지 보여줘요. %B 1.0 = 상단, 0 = 하단. '밴드 밖 = 무조건 반전'이 아니라 추세장에선 밴드를 타고 갑니다 — 초보가 가장 많이 걸리는 함정.",
    })

    # ── 4. RSI ───────────────────────────────────────────────────────────
    if rsi >= 70:
        st_, rd = f"RSI {rsi:.0f} — 과열권", "최근 14일 중 오른 날의 힘이 압도적이었다는 뜻. 다만 강한 추세에선 RSI 70 이상이 몇 주씩 유지되기도 해요 — '70 넘으면 팔아라'는 횡보장에서만 통하는 규칙."
    elif rsi <= 30:
        st_, rd = f"RSI {rsi:.0f} — 과매도권", "내린 날의 힘이 압도적이었어요. 기술적 반등이 자주 나오는 영역이지만, 악재로 인한 하락이면 30 아래에 오래 머물 수 있습니다."
    elif rsi >= 55:
        st_, rd = f"RSI {rsi:.0f} — 중립 상방", "매수세가 우위인 무난한 구간이에요."
    elif rsi <= 45:
        st_, rd = f"RSI {rsi:.0f} — 중립 하방", "매도세가 약간 우위인 구간이에요."
    else:
        st_, rd = f"RSI {rsi:.0f} — 중립", "힘의 균형 상태예요."
    out.append({
        "title": "⚡ RSI — 상승의 힘", "state": st_, "read": rd,
        "tip": "RSI = 최근 14일간 '오른 날의 상승폭'이 전체 등락폭에서 차지한 비율. 가격이 아니라 '힘의 비율'을 봐요. 차트 맨 아래 보라색 선이며, 점선(70/30)이 과열/과매도 기준선.",
    })

    # ── 5. MACD ──────────────────────────────────────────────────────────
    _dir = "커지는 중" if hist > hist_prev else "줄어드는 중"
    if hist > 0:
        st_, rd = f"히스토그램 + ({_dir})", \
            ("상승 모멘텀이 붙고 가속 중이에요." if hist > hist_prev else "상승 모멘텀은 남았지만 힘이 빠지는 중 — 추세 후반부 신호일 수 있어요.")
    else:
        st_, rd = f"히스토그램 − ({_dir})", \
            ("하락 모멘텀이 약해지는 중 — 바닥 다지기 초기에 자주 보여요." if hist > hist_prev else "하락 모멘텀이 진행 중이에요.")
    out.append({
        "title": "🌀 MACD — 추세의 가속도", "state": st_, "read": rd,
        "tip": "MACD는 단기(12일)와 장기(26일) 흐름의 간격. 히스토그램은 그 간격이 벌어지나 좁혀지나 = 추세의 '가속도'예요. 가격보다 먼저 방향 전환의 예고가 나타나는 경우가 많습니다.",
    })

    # ── 6. 거래량 ────────────────────────────────────────────────────────
    if rvol >= 2.0:
        st_, rd = f"평소의 {rvol:.1f}배 — 대량", "평소보다 훨씬 많은 손바뀜이 있었어요. 가격 움직임과 같은 방향의 대량 거래는 그 방향의 신뢰도를 크게 높입니다."
    elif rvol >= 1.3:
        st_, rd = f"평소의 {rvol:.1f}배 — 증가", "관심이 붙는 중이에요."
    elif rvol < 0.7:
        st_, rd = f"평소의 {rvol:.1f}배 — 한산", "관심이 식은 상태예요. 거래량 없는 상승/하락은 신뢰도가 낮습니다."
    else:
        st_, rd = f"평소의 {rvol:.1f}배 — 보통", "특이 신호 없는 평범한 수준이에요."
    if obv_up is not None:
        rd += " 누적 매집 흐름(OBV)은 20일 평균 " + ("위 — 사 모으는 쪽이 우세." if obv_up else "아래 — 파는 쪽이 우세.")
    out.append({
        "title": "📦 거래량 — 진짜 관심", "state": st_, "read": rd,
        "tip": "'가격은 속여도 거래량은 못 속인다.' 돌파가 진짜인지 가짜인지는 거래량이 판정해요. OBV는 오른 날 거래량을 더하고 내린 날 빼서 누적한 것 — 큰손이 조용히 사 모으면 가격보다 먼저 올라갑니다.",
    })

    return out


